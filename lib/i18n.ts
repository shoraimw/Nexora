export function translate(locale:Locale,source:string):string{
  if(locale==="en")return source;
  return bn[source]??source;
}

export function formatNumber(value:number,locale:Locale):string{
  return new Intl.NumberFormat(locale==="bn"?"bn-BD":"en-BD").format(value);
}

export function formatBDT(paisa:number,locale:Locale):string{
  return new Intl.NumberFormat(locale==="bn"?"bn-BD":"en-BD",{style:"currency",currency:"BDT",maximumFractionDigits:2}).format(paisa/100);
}

export function formatDate(value:Date|string|number,locale:Locale,options:Intl.DateTimeFormatOptions={}):string{
  const defaults=Object.keys(options).length===0?{dateStyle:"medium" as const}:{};
  return new Intl.DateTimeFormat(locale==="bn"?"bn-BD":"en-BD",{...defaults,...options}).format(new Date(value));
}
